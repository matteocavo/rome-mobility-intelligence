def test_repository_history_executes_typed_bounded_query(records):
    from contextlib import contextmanager

    session = Mock()
    now = datetime.now(timezone.utc)
    session.execute.return_value.mappings.return_value.all.return_value = [
        {**records[0].model_dump(), "id": 1, "created_at": now}
    ]

    @contextmanager
    def transaction():
        yield session

    database = Mock()
    database.session = transaction
    settings = Settings(_env_file=None)
    repo = PredictionHistoryRepository(database, settings)
    result = repo.history(HistoryQuery(limit=1))
    assert result[0].model_version == records[0].model_version
    assert result[0].created_at.tzinfo is not None
    compiled = session.execute.call_args.args[0].compile(dialect=postgresql.dialect())
    assert "SELECT" in str(compiled) and 1 in compiled.params.values()
    session.reset_mock()
    settings.history_max_rows = 1
    with pytest.raises(ValueError):
        repo.history(HistoryQuery(limit=2))
    session.execute.assert_not_called()


def test_alembic_offline_upgrade_downgrade_and_model_columns():
    output = io.StringIO()
    config = Config("alembic.ini", output_buffer=output)
    command.upgrade(config, "head", sql=True)
    ddl = output.getvalue()
    assert "CREATE TABLE public.prediction_history" in ddl
    assert "uq_prediction_history_source_model" in ddl
    for name in prediction_history.c.keys():
        assert name in ddl
    assert "CREATE INDEX ix_history_generated_id" in ddl
    output.seek(0)
    output.truncate()
    command.downgrade(config, "0001_prediction_history:base", sql=True)
    assert "DROP TABLE public.prediction_history" in output.getvalue()
