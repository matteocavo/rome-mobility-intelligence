def test_postgresql_specific_insert_ddl_and_minimization(records):
    statement = insert_statement(records).compile(dialect=postgresql.dialect())
    sql = str(statement)
    assert "ON CONFLICT ON CONSTRAINT uq_prediction_history_source_model DO NOTHING" in sql
    assert "RETURNING public.prediction_history.id" in sql
    ddl = str(CreateTable(prediction_history).compile(dialect=postgresql.dialect()))
    assert "UNIQUE (" + ", ".join(NATURAL_KEY) + ")" in ddl
    for name in NATURAL_KEY:
        assert not prediction_history.c[name].nullable
    assert "TIMESTAMP WITH TIME ZONE" in ddl and "GENERATED BY DEFAULT AS IDENTITY" in ddl
    assert "ck_history_probability" in ddl and "ck_history_decision" in ddl
    assert not {
        "feed_hour",
        "sql",
        "database_url",
        "artifact_path",
        "user_ip",
        "target_realized_major_delay_flag",
    } & set(prediction_history.c.keys())


def test_history_bind_values_order_range_and_limit():
    now = datetime.now(timezone.utc)
    query = HistoryQuery(
        route_id="'; DROP TABLE prediction_history; --", limit=200, predicted_major_delay=False
    )
    start, end = query.bounded_range(7, now)
    compiled = history_statement(query, start, end).compile(dialect=postgresql.dialect())
    sql = str(compiled)
    assert query.route_id not in sql and query.route_id in compiled.params.values()
    assert "prediction_generated_at DESC, public.prediction_history.id DESC" in sql
    assert end - start == timedelta(days=7) and 200 in compiled.params.values()
    with pytest.raises(ValueError):
        HistoryQuery.model_validate({"from": now, "to": now - timedelta(seconds=1)}).bounded_range(
            7
        )
    with pytest.raises(OverflowError):
        HistoryQuery.model_validate({"from": now - timedelta(days=8), "to": now}).bounded_range(7)


def test_session_rollback_before_sanitized_errors():
    database = Database(Settings(_env_file=None))
    database._engine = Mock()
    factory = MagicMock()
    session = factory.return_value.__enter__.return_value
    database._factory = factory
    transaction = session.begin.return_value
    with pytest.raises(DatabaseUnavailable, match="Application database unavailable") as caught:
        with database.session():
            raise OperationalError("private SQL", {}, Exception("private-host-password"))
    assert "private" not in str(caught.value)
    assert transaction.__exit__.call_args.args[0] is OperationalError
    with pytest.raises(DatabaseTimeout):
        with database.session():
            raise TimeoutError("private pool diagnostics")


