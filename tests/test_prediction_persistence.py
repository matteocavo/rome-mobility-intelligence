def test_insert_idempotence_model_upgrade_and_concurrent_simulation(records):
    database = FakeDatabase()
    repo = PredictionHistoryRepository(
        database, Settings(_env_file=None, enable_prediction_persistence=True)
    )
    assert repo.insert_batch(records) == 2
    assert repo.insert_batch(records) == 0
    newer = [r.model_copy(update={"model_version": "b" * 64}) for r in records]
    with ThreadPoolExecutor(max_workers=4) as pool:
        inserted = list(pool.map(lambda _: repo.insert_batch(newer), range(4)))
    assert sum(inserted) == 2 and len(database.rows) == 4


